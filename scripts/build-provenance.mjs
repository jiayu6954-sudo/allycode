import fs from "node:fs/promises";
import path from "node:path";
import { createHash } from "node:crypto";
const files = ["package.json", "package-lock.json", "tsup.config.ts", "update-sources.json", "account-service.json", "electron-builder.release.yml"];
async function walk(directory) {
  for (const entry of await fs.readdir(directory, { withFileTypes: true })) {
    const file = path.join(directory, entry.name);
    if (entry.isDirectory()) { if (!['node_modules','dist','dist-desktop','__pycache__','.venv'].includes(entry.name)) await walk(file); }
    else if (/\.(ts|tsx|css|json|html|py|ps1|sh|mjs|cjs|md|txt|yaml|yml|svg|png)$/.test(file) && !file.endsWith('build-info.ts')) files.push(file);
  }
}
await walk("src"); await walk("desktop"); await walk("skill/sources-to-excel-complete/sources-to-excel");
const hash = createHash("sha256");
for (const file of files.sort()) { hash.update(file.replaceAll('\\','/')); hash.update(await fs.readFile(file)); }
const pkg = JSON.parse(await fs.readFile("package.json", "utf8"));
const build = { version: pkg.version, sourceHash: hash.digest("hex"), builtAt: new Date().toISOString(), fileCount: files.length };
await fs.writeFile("src/build-info.ts", `// Generated by scripts/build-provenance.mjs\nexport const BUILD_INFO = ${JSON.stringify(build, null, 2)} as const;\n`);
await fs.mkdir(".tmp", { recursive: true });
await fs.writeFile(".tmp/build-provenance.json", JSON.stringify(build, null, 2));
console.log(`Build ${build.version} / ${build.sourceHash.slice(0,12)}`);
